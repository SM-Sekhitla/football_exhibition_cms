import { test,expect } from '@playwright/test';
import { adminPassword,proof,signIn } from './helpers';

test('registration requires prerequisites and POP, reaches another admin browser, then tracks approval',async({page,browser})=>{
  const name=`United ${Date.now()}`;
  await page.goto('/register');
  await expect(page.getByRole('heading',{name:'Before you register'})).toBeVisible();
  await page.getByRole('checkbox').check();
  await page.getByRole('button',{name:'Start team registration'}).click();
  await page.getByLabel('Team name',{exact:true}).fill(name);
  await page.getByLabel('Captain name').fill('Player 1');
  await page.getByLabel('Email address',{exact:true}).fill('captain@example.com');
  await page.getByLabel('City',{exact:true}).fill('Polokwane');
  await page.reload();
  await page.getByRole('checkbox').check();
  await page.getByRole('button',{name:'Start team registration'}).click();
  await expect(page.getByLabel('Team name',{exact:true})).toHaveValue(name);
  await page.getByRole('button',{name:'Continue',exact:true}).click();
  for(let i=1;i<=5;i++) await page.getByLabel(`Player ${i}`,{exact:true}).fill('Duplicate');
  await page.getByRole('button',{name:'Continue',exact:true}).click();
  await expect(page.getByRole('alert')).toContainText('listed once');
  for(let i=1;i<=5;i++) await page.getByLabel(`Player ${i}`,{exact:true}).fill(`Player ${i}`);
  await page.getByRole('button',{name:'Continue',exact:true}).click();
  await page.getByRole('checkbox').check();
  await page.getByRole('button',{name:'Submit application'}).click();
  await expect(page.getByTestId('application-reference')).toHaveCount(0);
  await page.getByLabel('Affiliation proof of payment (POP)').setInputFiles(proof);
  await page.getByRole('button',{name:'Submit application'}).click();
  const reference=await page.getByTestId('application-reference').innerText();
  const staffContext=await browser.newContext();const staff=await staffContext.newPage();
  await signIn(staff,'/admin/team-registrations');
  await staff.locator('article').filter({hasText:name}).getByRole('button',{name:'Review application'}).click();
  await expect(staff.getByRole('link',{name:'Download POP: proof.pdf'})).toHaveAttribute('href',/\/api\/v1\/files\//);
  await staff.getByLabel('Approval status').selectOption('Approved');
  await staff.getByLabel('Payment status').selectOption('Verified');
  await staff.getByLabel('Note to applicant').fill('Your place is confirmed.');
  await staff.getByRole('button',{name:'Save review'}).click();
  await staff.getByRole('button',{name:'Confirm',exact:true}).click();
  await expect(staff.getByRole('dialog')).toHaveCount(0);
  await page.goto('/teams');await expect(page.locator('main')).toContainText(name);
  await page.goto('/application-status');
  await page.getByLabel('Application reference').fill(reference);await page.getByLabel('Email address').fill('captain@example.com');
  await page.getByRole('button',{name:'Check status',exact:true}).click();
  await expect(page.locator('main')).toContainText('Your place is confirmed.');
  await staffContext.close();
});

test('banking requires server password confirmation and prerequisites are shared publicly',async({page,browser})=>{
  await signIn(page,'/admin/settings/registration');
  const originalBank=await page.getByLabel('Bank name',{exact:true}).inputValue();
  const originalText=await page.getByLabel('Prerequisites and required documents').inputValue();
  await page.getByLabel('Bank name',{exact:true}).fill('Updated bank');await page.getByLabel('Confirm admin password').fill('wrong');
  await page.getByRole('button',{name:'Save banking details'}).click();
  await expect(page.locator('main')).toContainText('Incorrect admin password');
  await page.getByLabel('Confirm admin password').fill(adminPassword);await page.getByRole('button',{name:'Save banking details'}).click();
  await expect(page.locator('main')).toContainText('Banking details saved.');
  await page.getByLabel('Prerequisites and required documents').fill('Have five players and your payment proof ready.');await page.getByRole('button',{name:'Save prerequisites'}).click();
  await expect(page.locator('main')).toContainText('Registration prerequisites saved.');
  const other=await browser.newContext();const publicPage=await other.newPage();await publicPage.goto('/register');
  await expect(publicPage.locator('main')).toContainText('Have five players and your payment proof ready.');await expect(publicPage.locator('main')).toContainText('Updated bank');
  await other.close();
  await page.getByLabel('Bank name',{exact:true}).fill(originalBank);await page.getByLabel('Confirm admin password').fill(adminPassword);await page.getByRole('button',{name:'Save banking details'}).click();
  await expect(page.getByLabel('Confirm admin password')).toHaveValue('');
  await page.getByLabel('Prerequisites and required documents').fill(originalText);await page.getByRole('button',{name:'Save prerequisites'}).click();
  await expect(page.locator('main')).toContainText('Registration prerequisites saved.');
});
